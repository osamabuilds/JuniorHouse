using Romp.BuildingBlocks.Domain;

namespace Romp.Modules.Catalog.Domain.ProductMedia;

/// <summary>
/// One image of a product, or of one colour of it (MED-8; the first image of a colour is that colour's main image). The original file is
/// stored under a generated key and its dimensions are kept so the page can reserve space (MED-10). Alt text may be empty while the
/// product is a draft; publishing needs a valid one on every image (SEO-07, MED-1). Maps to CTLG.PRDT_IMG.
/// </summary>
public sealed class ProductImage : Entity<long>, IAuditable
{
    private ProductImage()
    {
        FileKey = string.Empty;
        ContentType = string.Empty;
        OriginalFileName = string.Empty;
    }

    public ProductImage(long productId, short? colourId, string fileKey, string contentType, string originalFileName, int byteSize, int width, int height, int sortSeq, string? altText)
    {
        ProductId = productId;
        ColourId = colourId;
        FileKey = fileKey;
        ContentType = contentType;
        OriginalFileName = originalFileName;
        ByteSize = byteSize;
        Width = width;
        Height = height;
        SortSeq = sortSeq;
        AltText = string.IsNullOrWhiteSpace(altText) ? null : altText.Trim();
    }

    public long ProductId { get; private set; }

    /// <summary>The colour this image shows, or null for a product-level image.</summary>
    public short? ColourId { get; private set; }

    /// <summary>The storage key generated by <c>IFileStorage</c>; never derived from the client's file name (MED-9).</summary>
    public string FileKey { get; private set; }

    public string ContentType { get; private set; }

    /// <summary>The client's file name, kept only to name the image in messages (MED-1); never used to address the file.</summary>
    public string OriginalFileName { get; private set; }

    public int ByteSize { get; private set; }

    public int Width { get; private set; }

    public int Height { get; private set; }

    public int SortSeq { get; private set; }

    public string? AltText { get; private set; }

    public DateTimeOffset InsrDte { get; set; }

    public string InsrBy { get; set; } = string.Empty;

    public DateTimeOffset? UpdtDte { get; set; }

    public string? UpdtBy { get; set; }

    /// <summary>Sets the alt text after checking it (MED-2, MED-3). Null or blank clears it, which is allowed only while the product is a draft.</summary>
    public void SetAltText(string? text, bool allowEmpty)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            if (!allowEmpty)
            {
                throw new DomainException("A published product's image must keep its alt text.");
            }

            AltText = null;
            return;
        }

        var problem = ProductMedia.AltText.Validate(text);
        if (problem is not null)
        {
            throw new DomainException(problem);
        }

        AltText = text.Trim();
    }

    public void MoveTo(int sortSeq) => SortSeq = sortSeq;

    public bool HasValidAltText => ProductMedia.AltText.Validate(AltText) is null;
}
